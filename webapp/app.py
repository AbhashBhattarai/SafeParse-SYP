import os
import sys
import time
import secrets
from datetime import timedelta
from flask import (
    Flask, render_template, request, redirect,
    url_for, session, flash, abort
)
from werkzeug.security import generate_password_hash, check_password_hash
from db import get_db, close_db, init_db

# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

app = Flask(__name__)

secret_key = os.environ.get("FLASK_SECRET_KEY", "")
if not secret_key:
    print(
        "ERROR: FLASK_SECRET_KEY environment variable is not set.\n"
        "Generate one with PowerShell:\n"
        "  python -c \"import secrets; print(secrets.token_hex(32))\"\n"
        "Then set it:\n"
        "  $env:FLASK_SECRET_KEY = '<the value above>'"
    )
    sys.exit(1)

app.secret_key = secret_key
app.config["DEBUG"] = False
app.config["TEMPLATES_AUTO_RELOAD"] = True
app.config["SESSION_COOKIE_HTTPONLY"] = True
app.config["SESSION_COOKIE_SAMESITE"] = "Lax"
app.config["PERMANENT_SESSION_LIFETIME"] = timedelta(hours=1)

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
app.config["DATABASE"] = os.path.join(PROJECT_ROOT, "SafeParse_demo", "demo.db")

app.teardown_appcontext(close_db)

# ---------------------------------------------------------------------------
# Rate limiting: { (ip, username): [timestamp, ...] }
# ---------------------------------------------------------------------------
_failed_attempts = {}
_WINDOW = 300   # 5 minutes
_MAX_ATTEMPTS = 5
_BLOCK_DURATION = 300  # 5 minutes

def _get_attempts_key(ip, username):
    return (ip, username.lower())

def _is_blocked(ip, username):
    key = _get_attempts_key(ip, username)
    now = time.time()
    attempts = _failed_attempts.get(key, [])
    recent = [t for t in attempts if now - t < _WINDOW]
    _failed_attempts[key] = recent
    return len(recent) >= _MAX_ATTEMPTS

def _record_failure(ip, username):
    key = _get_attempts_key(ip, username)
    now = time.time()
    attempts = _failed_attempts.get(key, [])
    recent = [t for t in attempts if now - t < _WINDOW]
    recent.append(now)
    _failed_attempts[key] = recent

def _clear_attempts(ip, username):
    key = _get_attempts_key(ip, username)
    _failed_attempts.pop(key, None)

# ---------------------------------------------------------------------------
# CSRF helpers
# ---------------------------------------------------------------------------

def _generate_csrf():
    if "csrf_token" not in session:
        session["csrf_token"] = secrets.token_hex(32)
    return session["csrf_token"]

def _check_csrf():
    token = session.get("csrf_token", "")
    form_token = request.form.get("csrf_token", "")
    if not token or not form_token or token != form_token:
        abort(400)

# ---------------------------------------------------------------------------
# Before-request guard
# ---------------------------------------------------------------------------

PUBLIC_ENDPOINTS = {"login", "static", "register"}

@app.before_request
def require_login():
    if request.endpoint in PUBLIC_ENDPOINTS:
        return
    if "user_id" not in session:
        return redirect(url_for("login"))

